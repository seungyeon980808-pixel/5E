/** 그리기 요청 글: 장면 요청 + 정확해야 할 값 + 고칠 점. */
export function sceneRequestText({ request, keyValues = '', fixNote = '' }) {
  return request + (keyValues ? `\n정확해야 할 값: ${keyValues}` : '') + (fixNote ? `\n[앞서 그린 그림에서 고칠 점 — 반드시 반영]\n${fixNote}` : '');
}

