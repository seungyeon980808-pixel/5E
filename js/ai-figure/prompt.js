/** 찾은 설명 문장만 지운 그림 다시 만들기. */
export function stripRedrawPrompt(texts) {
  return `첨부 그림에서 아래 설명 문장만 깨끗이 지운 그림을 다시 만든다. 그 밖의 선·도형·라벨·배치·화풍은 그대로 둔다. 지운 자리는 흰 바탕으로, 남는 빈 여백은 잘라 낸다.\n지울 문장:\n- ${texts.join('\n- ')}`;
}
