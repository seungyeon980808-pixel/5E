import assert from 'node:assert/strict';
import { humanExamName, compareExamResults, createUnifiedLibraryProvider } from '../preview/js/library/provider.js';
import { cropContentBoundsForResult, commitAcceptedCropSession } from '../preview/js/unified-library-ui.js';
assert.equal(humanExamName({subject:'p1',academicYear:2008,administration:'06'}),'물리1 08년 6평');
assert.equal(humanExamName({subject:'c2',academicYear:2009,administration:'11'}),'화학2 09년 수능');
assert.equal(humanExamName({subject:'e1',academicYear:2014,administration:'09'}),'지구1 14년 9평');
const items = Array.from({length:620}, (_,i)=>({id:`q${i}`,subject:'p1',year:2027-Math.floor(i/20),month:'06',no:i%20+1,file:`q${i}.png`}));
const provider=createUnifiedLibraryProvider({examManifest:{items},examBaseUrl:'https://example.com/'});
const results=provider.search({kinds:['image'],limit:Number.MAX_SAFE_INTEGER});
assert.equal(results.length,620);
assert.deepEqual(results.slice(0,21).map(x=>[x.metadata.academicYear,x.metadata.itemNumber]), [...Array.from({length:20},(_,i)=>[2027,i+1]),[2026,1]]);
const question={kind:'crop',provenance:{documentId:'d',pageNumber:1,rect:[.1,.2,.3,.4]}};
const bounds=cropContentBoundsForResult(question,[{...question,provenance:{...question.provenance,rect:[.6,.7,.3,.2]}}]);
assert.ok(bounds.every((n,i)=>Math.abs(n-question.provenance.rect[i])<1e-9));
const entry=page=>({result:{id:`crop${page}`,provenance:{documentId:'d',pageNumber:page}}});
const acceptedAssets=new Map([['crop1',entry(1)]]),selectedIds=new Set(['crop1']),selectedRecords=new Map();
commitAcceptedCropSession({acceptedAssets,selectedIds,selectedRecords,acceptedCrops:[entry(2)],documentId:'d',pageNumber:2});
assert.equal(acceptedAssets.size,2);
assert.equal([...results].reverse().sort(compareExamResults)[0].metadata.academicYear,2027);
console.log('library-followup: labels, >500 results, exam ordering, target crop, cross-page preservation PASS');

const documents=Array.from({length:4},(_,i)=>({id:`pdf${i}`,title:`p1_${2027-i}_06`,pageCount:4,source:{kind:'pack',displayName:`p1_${2027-i}_06.pdf`}}));
const entries=documents.flatMap(d=>Array.from({length:20},(_,i)=>({documentId:d.id,pageNumber:Math.floor(i/5)+1,itemNumber:i+1,itemId:`q${i+1}`,text:`Question ${i+1}`,source:{documentId:d.id,pageNumber:Math.floor(i/5)+1,rect:[.1,.1,.3,.2],fullPageFallback:false}})));
const pdfProvider=createUnifiedLibraryProvider({pdfDocuments:documents,pdfSearchIndex:{entries}});
const questions=pdfProvider.search({kinds:['crop'],limit:Number.MAX_SAFE_INTEGER});
assert.equal(questions.length,80);
assert.deepEqual(questions.slice(0,21).map(q=>[q.metadata.academicYear,q.metadata.itemNumber]),[...Array.from({length:20},(_,i)=>[2027,i+1]),[2026,1]]);
assert.equal(pdfProvider.listPdfPages()[0].title,'물리1 27년 6평 · 1쪽');
console.log('library-followup: actual PDF crop inventory 80, questions 1–20 per exam, PDF page labels PASS');
