import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
const browser = await chromium.launch({headless:true});
const page = await browser.newPage({viewport:{width:1280,height:820}});
await page.goto(process.env.EDITOR_QA_URL || 'http://127.0.0.1:19783');
await page.getByRole('button',{name:'건너뛰기',exact:true}).click().catch(()=>{});
await page.locator('#bulk-edit-open').click();
await page.waitForTimeout(350);
await page.evaluate(async()=>{
  const {showConfirm}=await import('./js/ui-dialogs.js?v=1.4.0');
  window.escapeResult='pending';
  showConfirm('Nested confirmation',{cancelText:'계속 편집'}).then(value=>window.escapeResult=value);
});
await page.keyboard.press('Escape');
assert.equal(await page.evaluate(()=>window.escapeResult),false);
assert.equal(await page.locator('.bulk-modal').isVisible(),true);
assert.equal(await page.locator('#bulk-apply').evaluate(el=>el===document.activeElement),true);
await page.evaluate(()=>{document.body.tabIndex=-1;document.body.focus();});
await page.keyboard.press('Escape');
assert.equal(await page.locator('.bulk-modal').isVisible(),false);
assert.equal(await page.locator('#bulk-edit-open').evaluate(el=>el===document.activeElement),true);
await page.locator('#bulk-edit-open').click();
await page.evaluate(async()=>{
  const {showPrompt}=await import('./js/ui-dialogs.js?v=1.4.0');
  window.promptResult='pending';
  showPrompt('Unsaved text',{value:'keep original'}).then(value=>window.promptResult=value);
});
await page.evaluate(()=>document.body.focus());
await mkdir('.omo/evidence/editor-polish-all',{recursive:true});
await page.waitForTimeout(350);
await page.screenshot({path:'.omo/evidence/editor-polish-all/escape-nested-open.png'});
await page.keyboard.press('Escape');
assert.equal(await page.evaluate(()=>window.promptResult),null);
assert.equal(await page.locator('.bulk-modal').isVisible(),true);
await mkdir('.omo/evidence/editor-polish-all',{recursive:true});
await page.waitForTimeout(350);
await page.screenshot({path:'.omo/evidence/editor-polish-all/escape-nested.png'});
await page.screenshot({path:'.omo/evidence/editor-polish-all/escape-nested-after-esc.png'});
await writeFile('.omo/evidence/editor-polish-all/escape-results.json',JSON.stringify({nestedConfirm:false,underlyingBulkOpen:true,bodyFocusEscape:true,openerRestored:true,promptCancel:null},null,2));
await browser.close();
console.log('Esc nested confirmation, prompt cleanup, body focus and opener PASS');
