import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
const browser = await chromium.launch({headless:true});
const page = await browser.newPage({viewport:{width:1280,height:820}});
await page.route('**/index.html',async route=>{const response=await route.fetch();await route.fulfill({response,body:(await response.text()).replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi,'')})});
await page.goto('http://127.0.0.1:24897/index.html');
await page.evaluate(async()=>{
  const {createCanvasStore}=await import('/js/canvas-image-bounds.js');
  const {buildImageSection}=await import('/js/inspector/section-image.js');
  const {buildArtboardSection}=await import('/js/inspector/section-artboard.js');
  const c=document.createElement('canvas'); c.width=100;c.height=100;
  const ctx=c.getContext('2d');ctx.fillStyle='white';ctx.fillRect(0,0,100,100);ctx.fillStyle='black';ctx.fillRect(20,30,60,40);ctx.fillStyle='white';ctx.fillRect(35,40,20,15);
  window.qaStore=createCanvasStore({objects:[{id:'qa',type:'image',src:c.toDataURL(),x:-25,y:-25,w:50,h:50}],selectedIds:['qa'],undoStack:[],redoStack:[],artboard:{w:90,h:60},activePageId:'qa',viewBox:{x:-55,y:-40,w:110,h:80},layers:[],grid:{visible:false}});
  document.body.replaceChildren();
  document.body.style.cssText='display:flex;padding:30px;gap:24px;background:#161c22;color:#ddd';
  const controls=document.createElement('div');controls.style.cssText='width:290px';
  controls.append(buildImageSection({state:qaStore,snapBefore:()=>[],pushSnap:()=>{}}).imageSection);
  controls.append(buildArtboardSection({state:qaStore}).abSection);
  const canvas=document.createElementNS('http://www.w3.org/2000/svg','svg');canvas.setAttribute('viewBox','-55 -40 110 80');canvas.style.cssText='position:fixed;left:350px;top:50px;width:850px;height:650px;display:block;max-width:none;max-height:none';canvas.innerHTML='<g id="scene"></g>';
  document.body.append(controls,canvas);
  const {render}=await import('/js/render/scene.js');qaStore.subscribe(render);render(qaStore.get());
  document.querySelectorAll('details').forEach(d=>d.open=true);
});
await page.getByRole('button',{name:'외부 여백 제거',exact:true}).click();
await page.waitForFunction(()=>window.qaStore.get().undoStack.length===1);
let result=await page.evaluate(()=>{const s=qaStore.get();return {o:s.objects[0],undo:s.undoStack[0][0]}});
assert.equal(result.o.w,30);assert.equal(result.o.h,20);assert.equal(result.o.src,result.undo.src);assert.deepEqual(result.o.srcRect,{x:.2,y:.3,w:.6,h:.4});
await page.getByLabel('아트보드 배경 표시').selectOption('checkerboard');
assert.equal(await page.locator('#scene > rect').first().getAttribute('fill'),'url(#artboard-display-checker)');
await page.getByLabel('이미지를 캔버스 안으로 제한').check();
result=await page.evaluate(()=>{qaStore.update(s=>{s.objects[0].x=100;s.objects[0].y=100;s.objects[0].w=150;s.objects[0].rotation=45});return qaStore.get().objects[0]});
const rad=Math.PI/4, w=result.w*Math.cos(rad)+result.h*Math.sin(rad),h=result.w*Math.sin(rad)+result.h*Math.cos(rad);
assert.ok(result.x+result.w/2+w/2<=45.00001);assert.ok(result.y+result.h/2+h/2<=30.00001);
await page.evaluate(()=>qaStore.update(s=>{s.objects=s.undoStack.pop()}));
assert.equal(await page.evaluate(()=>qaStore.get().objects[0].w),50);
await page.evaluate(()=>{qaStore.update(s=>{s.redoStack.push([{...s.objects[0],x:100}])});qaStore.update(s=>{s.undoStack.push(s.objects);s.objects=s.redoStack.pop()})});
assert.equal(await page.evaluate(()=>qaStore.get().objects[0].x),100);
await page.evaluate(()=>qaStore.update(s=>{s.objects=s.undoStack.pop()}));
await page.evaluate(()=>qaStore.update(s=>{s.pages=[{id:s.activePageId}];s.objects=[{...s.objects[0],x:120}];s.undoStack=[];s.redoStack=[]}));
assert.equal(await page.evaluate(()=>qaStore.get().objects[0].x),120);
await page.evaluate(()=>qaStore.update(s=>{s.objects[0].x=-25}));
const exportContains=await page.evaluate(async()=>{const {buildExportSvg}=await import('/js/svg-export.js');return new XMLSerializer().serializeToString(buildExportSvg(qaStore.get())).includes('artboard-display-checker')});
assert.equal(exportContains,false);
await mkdir('.omo/evidence/canvas-image-options',{recursive:true});
await page.screenshot({path:'.omo/evidence/canvas-image-options/options.png'});
