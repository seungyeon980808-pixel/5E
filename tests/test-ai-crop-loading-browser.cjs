const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium, webkit } = require('playwright');
const { installCropFixture, pointerOnImage } = require('./helpers/crop-loading-fixture.cjs');
const verifyToolLenses = require('./helpers/crop-tool-lenses.cjs');
const verifyPreviewLoading = require('./helpers/crop-preview-loading.cjs');
const evidence = path.resolve(process.env.EVIDENCE_DIR || '.omo/evidence/ai-workbench-polish-0928/task4/magnifier');
const closeTo = (actual, expected, message) => assert.ok(Math.abs(actual - expected) < .1, `${message}: ${actual} != ${expected}`);

async function lensCoordinates(page, ui) {
  const { image, point } = await pointerOnImage(page, ui);
  const lens = page.locator('#library-crop-magnifier');
  await lens.waitFor({ state: 'visible' });
  const view = (await lens.locator('svg').first().getAttribute('viewBox')).split(' ').map(Number);
  const natural = await ui.locator('[data-unilib-crop-image]').evaluate(img => ({ width: img.naturalWidth, height: img.naturalHeight }));
  closeTo(view[0] + view[2] / 2, (point.x - image.x) / image.width * natural.width, 'raster x');
  closeTo(view[1] + view[3] / 2, (point.y - image.y) / image.height * natural.height, 'raster y');
  closeTo(view[2], 158 / 8 * natural.width / image.width, '8x screen magnification');
  const box = await lens.boundingBox();
  closeTo(box.width, 160, 'lens width independent of device pixels');
  assert.ok(box.x >= 8 && box.y >= 8 && box.x + box.width <= 1592 && box.y + box.height <= 992, 'lens remains inside viewport');
  assert.equal(await lens.locator('path').count(), 2);
}

(async () => {
  fs.mkdirSync(evidence, { recursive: true });
  const outcomes = [];
  for (const [name, engine] of Object.entries({ chromium, webkit })) {
    const browser = await engine.launch({ headless: true });
    const context = await browser.newContext({ viewport: { width: 1600, height: 1000 }, deviceScaleFactor: 2, hasTouch: true });
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    try {
      const ui = await installCropFixture(page);
      const load = ui.locator('[data-unilib-crop-load-state]');
      const stage = ui.locator('[data-unilib-crop-stage]');
      const toggle = ui.locator('[data-crop-magnifier-toggle]');
      assert.equal(await toggle.isChecked(), false, 'library default-off');
      await toggle.check();
      await lensCoordinates(page, ui);
      await page.screenshot({ path: path.join(evidence, `${name}-raster-lens.png`) });
      await ui.locator('[data-unilib-crop-zoom-in]').click();
      await lensCoordinates(page, ui);
      await stage.evaluate(el => { el.scrollTop += 80; el.scrollLeft += 35; });
      await page.locator('#library-crop-magnifier').waitFor({ state: 'hidden' });
      await lensCoordinates(page, ui);
      await pointerOnImage(page, ui, .99);
      await page.screenshot({ path: path.join(evidence, `${name}-zoom-edge.png`) });
      await toggle.uncheck();
      await pointerOnImage(page, ui);
      await page.locator('#library-crop-magnifier').waitFor({ state: 'hidden' });
      await ui.locator('[data-unilib-crop-cancel]').click();
      await ui.locator('[data-unilib-adjust]').click();
      await load.waitFor({ state: 'hidden' });
      assert.equal(await toggle.isChecked(), false, 'preference retained on reopen');
      await toggle.check();
      await lensCoordinates(page, ui);
      const touch = await pointerOnImage(page, ui);
      await page.touchscreen.tap(touch.point.x, touch.point.y);
      await page.locator('#library-crop-magnifier').waitFor({ state: 'hidden' });
      await lensCoordinates(page, ui);
      await stage.focus();
      await page.keyboard.down('Space');
      await page.locator('#library-crop-magnifier').waitFor({ state: 'hidden' });
      await page.keyboard.up('Space');
      await page.evaluate(() => { window.holdCrop('original-2'); window.holdCrop('thumbnail-2'); });
      await ui.locator('[data-unilib-crop-page-next]').click();
      await load.waitFor({ state: 'visible' });
      const paper = ui.locator('.unilib-crop-load-paper');
      await paper.waitFor({ state: 'visible' });
      const pending = await paper.boundingBox();
      closeTo(pending.width / pending.height, 2, 'landscape target skeleton ratio');
      assert.equal(await ui.locator('[data-unilib-crop-image]').isVisible(), false, 'previous page hidden');
      assert.equal(await ui.evaluate(el => getComputedStyle(el, '::after').backdropFilter), 'none', 'no crop backdrop blur');
      await page.screenshot({ path: path.join(evidence, `${name}-neutral-landscape.png`) });
      await page.evaluate(() => { window.cropGates['thumbnail-2'].release(); });
      await ui.locator('.unilib-crop-load-preview').waitFor({ state: 'visible' });
      const target = await ui.locator('.unilib-crop-load-preview').boundingBox();
      closeTo(target.width, pending.width, 'thumbnail preserves target width');
      closeTo(target.height, pending.height, 'thumbnail preserves target height');
      assert.equal(await ui.locator('.unilib-crop-load-preview').evaluate(el => getComputedStyle(el).filter), 'blur(1.5px)');
      assert.equal(await ui.locator('[data-unilib-crop-canvas]').evaluate(el => getComputedStyle(el).filter), 'none');
      await page.screenshot({ path: path.join(evidence, `${name}-target-loading.png`) });
      await page.evaluate(() => { window.holdCrop('decode-2'); window.cropGates['original-2'].release(); });
      await page.evaluate(async () => { for (let i = 0; i < 4; i++) await new Promise(requestAnimationFrame); });
      assert.equal(await load.isVisible(), true, 'status remains during decoded readiness');
      await page.evaluate(() => window.cropGates['decode-2'].release());
      await load.waitFor({ state: 'hidden' });
      const ready = await ui.locator('[data-unilib-crop-image]').boundingBox();
      closeTo(ready.width, target.width, 'ready width matches loading');
      closeTo(ready.height, target.height, 'ready height matches loading');
      await lensCoordinates(page, ui);
      await page.screenshot({ path: path.join(evidence, `${name}-landscape-ready.png`) });
      await page.evaluate(() => { window.cropBrokenPage = 3; });
      await ui.locator('[data-unilib-crop-page-next]').click();
      await ui.locator('[data-unilib-crop-load-state][data-state="error"]').waitFor();
      await page.screenshot({ path: path.join(evidence, `${name}-decode-error.png`) });
      await page.evaluate(() => { window.cropBrokenPage = null; });
      await ui.locator('[data-unilib-crop-retry]').click();
      await load.waitFor({ state: 'hidden' });
      assert.equal(await ui.locator('[data-unilib-crop-image]').evaluate(img => img.naturalWidth), 700, 'retry renders actual target');
      await page.evaluate(() => { window.holdCrop('original-2'); window.holdCrop('thumbnail-2'); });
      await ui.locator('[data-unilib-crop-page-prev]').click();
      await load.waitFor({ state: 'visible' });
      await ui.locator('[data-unilib-crop-cancel]').click();
      await ui.locator('[data-result-id="geometry-book:page:1"]').click();
      await ui.locator('[data-unilib-adjust]').click();
      await load.waitFor({ state: 'hidden' });
      await page.evaluate(async () => { window.cropGates['original-2'].release(); window.cropGates['thumbnail-2'].release(); for (let i = 0; i < 4; i++) await new Promise(requestAnimationFrame); });
      assert.equal(await ui.locator('[data-unilib-crop-image]').evaluate(img => img.naturalWidth), 600, 'stale page cannot replace reopened target');
      assert.equal(await ui.locator('.unilib-crop-load-preview').getAttribute('src'), null);
      await lensCoordinates(page, ui);
      const sourceOnly = await page.evaluate(() => {
        const img = document.querySelector('[data-unilib-crop-image]');
        const canvas = document.createElement('canvas'); canvas.width = img.naturalWidth; canvas.height = img.naturalHeight;
        canvas.getContext('2d').drawImage(img, 0, 0);
        return { original: window.cropSources[1], exported: canvas.toDataURL(), lensInSource: img.contains(document.querySelector('#library-crop-magnifier')) };
      });
      assert.equal(sourceOnly.exported, sourceOnly.original, 'visible lens does not alter exported source pixels');
      assert.equal(sourceOnly.lensInSource, false);
      await ui.locator('[data-unilib-crop-cancel]').click();
      await page.locator('#library-crop-magnifier').waitFor({ state: 'hidden' });
      await page.evaluate(() => window.cropFixture.close());
      await verifyPreviewLoading(page, evidence, name);
      await verifyToolLenses(page, evidence, name);
      await page.locator('#panel-right [data-crop-magnifier-toggle]').uncheck();
      await page.reload();
      let reopened = await installCropFixture(page);
      assert.equal(await reopened.locator('[data-crop-magnifier-toggle]').isChecked(), true, 'canvas preference does not change library preference');
      await reopened.locator('[data-crop-magnifier-toggle]').uncheck();
      await page.reload();
      reopened = await installCropFixture(page);
      assert.equal(await reopened.locator('[data-crop-magnifier-toggle]').isChecked(), false, 'preference survives document reload');
      await reopened.locator('[data-unilib-crop-cancel]').click();
      await page.evaluate(() => window.cropFixture.close());
      assert.deepEqual(errors, []);
      outcomes.push({ engine: name, deviceScaleFactor: 2, result: 'PASS', scenarios: ['raster zoom pan edge', 'SVG coordinates and UI zoom', 'persistent toggle and document reload', 'ordinary preview decode and previous-page exclusion', 'cut and delayed-cut inspector', 'capture adapter lifecycle', 'touch and Space hiding', 'neutral landscape geometry', 'target-only blur', 'decoded readiness', 'decode error retry', 'close reopen stale response', 'export pixels', 'destroy'] });
    } catch (error) {
      await page.screenshot({ path: path.join(evidence, `${name}-failure.png`) });
      throw error;
    } finally { await context.close(); await browser.close(); }
  }
  fs.writeFileSync(path.join(evidence, 'results.json'), JSON.stringify(outcomes, null, 2));
  console.log(JSON.stringify(outcomes));
})().catch(error => { console.error(error); process.exitCode = 1; });
