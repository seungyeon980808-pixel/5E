"""공유 자료 PDF 쪽 미리보기(assets/pdf-library/previews/<sha>/<쪽>[-thumb].webp)를 만들고 manifest.js에 더한다.

옛 도구 tools/pdf-library/build-page-previews.mjs(857914e6·d982c73a)와 같은 규격이다:
긴 변 1000px로 그려 JPEG(품질 90)를 거쳐 cwebp 품질 68, 썸네일은 높이 320px. CropBox 기준(PyMuPDF 기본).
pdftoppm 대신 PyMuPDF로 그린다(이 맥에 poppler가 없음). 이미 있는 sha 폴더는 건드리지 않는다.

실행: python3 -I tools/pdf-library/build-page-previews.py <PDF> [<PDF> ...]
필요: PyMuPDF, Pillow, cwebp(brew install webp)
그 뒤 5e-images Worker에 올려야 웹·설치판이 받는다(cloudflare/images/README.md).
"""
from __future__ import annotations

import hashlib
import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path

import pymupdf
from PIL import Image

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "assets" / "pdf-library" / "previews"
MANIFEST = OUT / "manifest.js"
HEAD = "// Generated by tools/pdf-library/build-page-previews.mjs. Keys identify immutable PDF bytes.\n"


def read_manifest() -> dict[str, int]:
    text = MANIFEST.read_text(encoding="utf-8")
    match = re.search(r"Object\.freeze\((\{.*\})\);", text, re.S)
    if not match:
        raise SystemExit("manifest.js 모양을 읽지 못했습니다.")
    return json.loads(match.group(1))


def build(pdf: Path, manifest: dict[str, int]) -> tuple[str, int]:
    data = pdf.read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    target = OUT / digest
    if digest in manifest and target.is_dir():
        return digest, 0
    target.mkdir(parents=True, exist_ok=True)
    with pymupdf.open(stream=data, filetype="pdf") as doc, tempfile.TemporaryDirectory() as temp:
        for number, page in enumerate(doc, 1):
            scale = 1000 / max(page.rect.width, page.rect.height)
            pix = page.get_pixmap(matrix=pymupdf.Matrix(scale, scale), colorspace=pymupdf.csRGB, alpha=False)
            jpeg = Path(temp) / f"page-{number}.jpg"
            Image.frombytes("RGB", (pix.width, pix.height), pix.samples).save(jpeg, "JPEG", quality=90)
            full = target / f"{number}.webp"
            subprocess.run(["cwebp", "-quiet", "-q", "68", str(jpeg), "-o", str(full)], check=True)
            subprocess.run(["cwebp", "-quiet", "-q", "68", "-resize", "0", "320", str(full), "-o", str(target / f"{number}-thumb.webp")], check=True)
        manifest[digest] = len(doc)
        return digest, len(doc)


def main(paths: list[str]) -> None:
    if not paths:
        raise SystemExit(__doc__)
    manifest = read_manifest()
    for path in paths:
        digest, pages = build(Path(path), manifest)
        print(f"{Path(path).name}\t{digest}\t{'이미 있음' if pages == 0 else f'{pages}쪽'}")
    MANIFEST.write_text(f"{HEAD}export const providedPagePreviews = Object.freeze({json.dumps(manifest, separators=(',', ':'))});\n", encoding="utf-8")


if __name__ == "__main__":
    main(sys.argv[1:])
