import { readFile, writeFile, mkdir, readdir, rm, stat } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import path from 'node:path';
import os from 'node:os';

const run = promisify(execFile);
const [specPath, outputPath] = process.argv.slice(2);
if (!specPath || !outputPath) throw new Error('Usage: node build-page-previews.mjs spec.json output-directory');
const spec = JSON.parse(await readFile(specPath, 'utf8'));
const output = path.resolve(outputPath);
await mkdir(output, { recursive: true });
const manifest = {};
let cursor = 0;
let pageCount = 0;
let bytes = 0;
async function worker() {
  while (cursor < spec.documents.length) {
    const document = spec.documents[cursor++];
    const hash = createHash('sha256').update(await readFile(document.source)).digest('hex');
    const temporary = path.join(os.tmpdir(), `5e-page-previews-${process.pid}-${hash}`);
    await mkdir(temporary, { recursive: true });
    const target = path.join(output, hash);
    await mkdir(target, { recursive: true });
    try {
      await run('pdftoppm', ['-cropbox', '-scale-to', '1000', '-jpeg', '-jpegopt', 'quality=90', document.source, path.join(temporary, 'page')]);
      const files = (await readdir(temporary)).filter(name => /^page-\d+\.jpg$/.test(name));
      for (const file of files) {
        const page = Number(file.match(/(\d+)\.jpg$/)[1]);
        const destination = path.join(target, `${page}.webp`);
        await run('cwebp', ['-quiet', '-q', '68', path.join(temporary, file), '-o', destination]);
        const thumbnail = path.join(target, `${page}-thumb.webp`);
        await run('cwebp', ['-quiet', '-q', '68', '-resize', '0', '320', destination, '-o', thumbnail]);
        bytes += (await stat(destination)).size + (await stat(thumbnail)).size;
        pageCount++;
      }
      manifest[hash] = files.length;
    } finally {
      await rm(temporary, { recursive: true, force: true });
    }
  }
}
await Promise.all(Array.from({ length: 4 }, worker));
await writeFile(path.join(output, 'manifest.js'), `// Generated by tools/pdf-library/build-page-previews.mjs. Keys identify immutable PDF bytes.\nexport const providedPagePreviews = Object.freeze(${JSON.stringify(manifest)});\n`);
console.log(JSON.stringify({ documents: Object.keys(manifest).length, pageCount, bytes, output }));
